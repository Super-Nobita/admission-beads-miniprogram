const fs = require('fs')
const path = require('path')
const { GENERATED_LOGO_SOURCES } = require('../data/schoolLogoSources.generated')

const ASSET_DIR = path.resolve(__dirname, '../assets/school-logos')
const OUTPUT_PATH = path.resolve(__dirname, '../data/schoolLogoCache.generated.js')
const MAX_LOGOS = Number(process.env.MAX_LOGOS || 50)

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

const slugify = (value) => value
  .normalize('NFKD')
  .replace(/[^\w\u4e00-\u9fa5-]+/g, '-')
  .replace(/-+/g, '-')
  .replace(/^-|-$/g, '')

const extFromContentType = (contentType) => {
  const type = String(contentType || '').toLowerCase()
  if (type.includes('image/png')) return 'png'
  if (type.includes('image/jpeg')) return 'jpg'
  if (type.includes('image/webp')) return 'webp'
  if (type.includes('image/svg')) return 'svg'
  return ''
}

const extFromUrl = (url) => {
  const match = String(url || '').toLowerCase().match(/\.(png|jpg|jpeg|webp|svg)(?:[?#].*)?$/)
  if (!match) return ''
  return match[1] === 'jpeg' ? 'jpg' : match[1]
}

const isSupportedImage = (ext) => ['png', 'jpg', 'webp', 'svg'].includes(ext)

const normalizeUrl = (url) => {
  if (!url) return ''
  if (url.startsWith('http')) return url
  if (url.startsWith('//')) return `https:${url}`
  if (url.startsWith('/')) return `https://www.urongda.com${url}`
  return url
}

const findPreviewImageUrl = async (record) => {
  if (!record.sourceUrl) return ''
  const res = await fetch(record.sourceUrl, {
    redirect: 'follow',
    headers: {
      'user-agent': 'Mozilla/5.0 school-logo-cache'
    }
  })
  if (!res.ok) return ''

  const html = await res.text()
  const candidates = []
  const imagePattern = /(?:https?:\/\/[^"'\s]+|\/[^"'\s]+)\/images\/normal\/medium\/[^"'\s]+?\.(?:png|jpg|jpeg|webp|svg)/gi
  let match = imagePattern.exec(html)
  while (match) {
    candidates.push(normalizeUrl(match[0]))
    match = imagePattern.exec(html)
  }

  return candidates.find((url) => url.includes('1024')) ||
    candidates.find((url) => url.includes('512')) ||
    candidates[0] ||
    ''
}

const cacheOne = async (record, index) => {
  const previewImageUrl = record.imageUrl || await findPreviewImageUrl(record)
  const sourceUrl = previewImageUrl || record.downloadUrl
  if (!sourceUrl) {
    return Object.assign({}, record, {
      cacheStatus: 'missing_source',
      localPath: ''
    })
  }

  const res = await fetch(sourceUrl, {
    redirect: 'follow',
    headers: {
      'user-agent': 'Mozilla/5.0 school-logo-cache'
    }
  })
  const contentType = res.headers.get('content-type') || ''
  const ext = extFromContentType(contentType) || extFromUrl(res.url) || extFromUrl(sourceUrl)
  if (!res.ok || !isSupportedImage(ext)) {
    return Object.assign({}, record, {
      cacheStatus: 'not_direct_image',
      cacheMessage: `HTTP ${res.status} ${contentType}`.trim(),
      localPath: ''
    })
  }

  const arrayBuffer = await res.arrayBuffer()
  const fileName = `${String(index + 1).padStart(4, '0')}-${slugify(record.school)}.${ext}`
  const absolutePath = path.join(ASSET_DIR, fileName)
  fs.mkdirSync(ASSET_DIR, { recursive: true })
  fs.writeFileSync(absolutePath, Buffer.from(arrayBuffer))

  return Object.assign({}, record, {
    status: 'local_cached',
    imageUrl: previewImageUrl,
    localPath: `/assets/school-logos/${fileName}`,
    cacheStatus: 'ok',
    cacheMessage: ''
  })
}

const serialize = (records) => `// Auto-generated by tools/cache-school-logo-files.js
// Local files are stored under assets/school-logos.

const GENERATED_LOGO_CACHE = ${JSON.stringify(records, null, 2)}

module.exports = {
  GENERATED_LOGO_CACHE
}
`

const main = async () => {
  const sourceRecords = GENERATED_LOGO_SOURCES
    .filter((record) => record.imageUrl || record.downloadUrl)
    .slice(0, MAX_LOGOS)

  const cacheRecords = []
  for (let index = 0; index < sourceRecords.length; index += 1) {
    const record = sourceRecords[index]
    process.stdout.write(`Caching ${record.school}... `)
    const cached = await cacheOne(record, index)
    cacheRecords.push(cached)
    process.stdout.write(`${cached.cacheStatus}\n`)
    await sleep(250)
  }

  fs.writeFileSync(OUTPUT_PATH, serialize(cacheRecords), 'utf8')
  const cachedCount = cacheRecords.filter((record) => record.cacheStatus === 'ok').length
  console.log(`Wrote ${cacheRecords.length} cache records to ${OUTPUT_PATH}`)
  console.log(`Cached ${cachedCount} local logo files`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
