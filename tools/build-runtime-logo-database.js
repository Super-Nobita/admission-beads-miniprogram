const fs = require('fs')
const path = require('path')
const { SCHOOL_LOGO_DATABASE } = require('../data/schoolLogoDatabase.generated')

const OUTPUT_PATH = path.resolve(__dirname, '../data/schoolLogoRuntime.generated.js')

const runtimeRecords = SCHOOL_LOGO_DATABASE.map((record) => ({
  school: record.school,
  province: record.province || '',
  type: record.type || '',
  status: record.status,
  sourceName: record.sourceName || '',
  sourceUrl: record.sourceUrl || '',
  imageUrl: record.imageUrl || '',
  cachedFileID: record.cachedFileID || '',
  aliasOf: record.aliasOf || ''
}))

const js = `// Auto-generated by tools/build-runtime-logo-database.js
// Compact app-facing logo index. Heavy local cache metadata is intentionally excluded.

const SCHOOL_LOGO_RUNTIME_DATABASE = ${JSON.stringify(runtimeRecords, null, 2)}

const SCHOOL_LOGO_RUNTIME_DATABASE_MAP = SCHOOL_LOGO_RUNTIME_DATABASE.reduce((map, item) => {
  map[item.school] = item
  return map
}, {})

module.exports = {
  SCHOOL_LOGO_RUNTIME_DATABASE,
  SCHOOL_LOGO_RUNTIME_DATABASE_MAP
}
`

fs.writeFileSync(OUTPUT_PATH, js, 'utf8')

const ready = runtimeRecords.filter((record) => record.cachedFileID || record.imageUrl).length
console.log(`Wrote ${runtimeRecords.length} runtime logo records`)
console.log(`Runtime image-ready records: ${ready}`)
console.log(OUTPUT_PATH)
