const fs = require('fs')
const path = require('path')
const { SCHOOL_CATALOG } = require('../data/schools')
const { NATIONAL_SCHOOLS } = require('../data/nationalSchools.generated')
const { GENERATED_LOGO_SOURCES } = require('../data/schoolLogoSources.generated')
const { GENERATED_LOGO_CACHE } = require('../data/schoolLogoCache.generated')
const { SCHOOL_LOGO_ALIASES } = require('../data/schoolLogoAliases')

const JS_OUTPUT_PATH = path.resolve(__dirname, '../data/schoolLogoDatabase.generated.js')
const JSON_OUTPUT_PATH = path.resolve(__dirname, '../data/schoolLogoDatabase.generated.json')

const OFFICIAL_SOURCES = {
  清华大学: {
    status: 'official_source',
    sourceName: '清华大学视觉形象识别系统',
    sourceUrl: 'https://vi.tsinghua.edu.cn/gk/xxbz/xh.htm',
    licenseNote: '需按学校视觉形象识别系统规范使用'
  },
  北京大学: {
    status: 'official_source',
    sourceName: '北京大学标识管理办公室',
    sourceUrl: 'https://vim.pku.edu.cn/xzzq/index.htm',
    licenseNote: '需按北京大学标识管理办公室规范使用'
  },
  浙江大学: {
    status: 'official_source',
    sourceName: '浙江大学学校标识',
    sourceUrl: 'https://www.zju.edu.cn/_t3007/xx1/list.psp',
    licenseNote: '需按浙江大学学校标识规范使用'
  },
  复旦大学: {
    status: 'official_source',
    sourceName: '复旦大学标识下载',
    sourceUrl: 'https://www.fudan.edu.cn/fdbsxz/list.htm',
    licenseNote: '需按复旦大学标识系统规范使用'
  }
}

const defaultRecord = (school) => ({
  school: school.name,
  province: school.province || '待补充',
  type: school.type || '综合',
  level: school.level || '',
  city: school.city || '',
  department: school.department || '',
  code: school.code || '',
  status: 'source_pending',
  sourceName: '',
  sourceUrl: '',
  imageUrl: '',
  localPath: '',
  downloadUrl: '',
  cachedFileID: '',
  cacheStatus: 'pending',
  cacheMessage: '',
  licenseNote: '待采集官方来源和使用规范'
})

const bySchool = new Map()

const masterSchools = NATIONAL_SCHOOLS.length > 0
  ? NATIONAL_SCHOOLS.map((school) => ({
    name: school.name,
    province: school.province,
    type: school.level || school.type,
    city: school.city,
    code: school.code,
    department: school.department
  }))
  : SCHOOL_CATALOG

masterSchools.forEach((school) => {
  bySchool.set(school.name, defaultRecord(school))
})

GENERATED_LOGO_SOURCES.forEach((record) => {
  const base = bySchool.get(record.school) || defaultRecord({
    name: record.school,
    province: record.province,
    type: record.type
  })
  bySchool.set(record.school, Object.assign(base, record))
})

GENERATED_LOGO_CACHE.forEach((record) => {
  const base = bySchool.get(record.school) || defaultRecord({
    name: record.school,
    province: record.province,
    type: record.type
  })
  bySchool.set(record.school, Object.assign(base, record))
})

Object.keys(OFFICIAL_SOURCES).forEach((school) => {
  if (!bySchool.has(school)) return
  bySchool.set(school, Object.assign(bySchool.get(school), OFFICIAL_SOURCES[school]))
})

Object.keys(SCHOOL_LOGO_ALIASES).forEach((school) => {
  const targetSchool = SCHOOL_LOGO_ALIASES[school]
  const base = bySchool.get(school)
  const target = bySchool.get(targetSchool)
  if (!base || !target) return
  const hasLogo = target.localPath || target.cachedFileID || target.imageUrl
  const alreadyReady = base.localPath || base.cachedFileID || base.imageUrl
  if (!hasLogo || alreadyReady) return

  bySchool.set(school, Object.assign({}, base, {
    status: target.status,
    sourceName: target.sourceName,
    sourceUrl: target.sourceUrl,
    imageUrl: target.imageUrl,
    localPath: target.localPath,
    downloadUrl: target.downloadUrl,
    cachedFileID: target.cachedFileID,
    cacheStatus: target.cacheStatus,
    cacheMessage: target.cacheMessage,
    aliasOf: targetSchool,
    licenseNote: target.licenseNote || base.licenseNote
  }))
})

const SCHOOL_LOGO_DATABASE = Array.from(bySchool.values())
  .sort((a, b) => a.school.localeCompare(b.school, 'zh-CN'))
  .map((record) => ({
    school: record.school,
    province: record.province || '待补充',
    type: record.type || '综合',
    level: record.level || '',
    city: record.city || '',
    department: record.department || '',
    code: record.code || '',
    status: record.localPath || record.cachedFileID || record.imageUrl ? 'ready' : 'logo_missing',
    sourceName: record.sourceName || '',
    sourceUrl: record.sourceUrl || '',
    imageUrl: record.imageUrl || '',
    localPath: record.localPath || '',
    downloadUrl: record.downloadUrl || '',
    cachedFileID: record.cachedFileID || '',
    cacheStatus: record.cacheStatus || '',
    cacheMessage: record.cacheMessage || '',
    aliasOf: record.aliasOf || '',
    licenseNote: record.licenseNote || ''
  }))

const js = `// Auto-generated by tools/build-school-logo-database.js
// This is the app-facing school logo database.

const SCHOOL_LOGO_DATABASE = ${JSON.stringify(SCHOOL_LOGO_DATABASE, null, 2)}

const SCHOOL_LOGO_DATABASE_MAP = SCHOOL_LOGO_DATABASE.reduce((map, item) => {
  map[item.school] = item
  return map
}, {})

module.exports = {
  SCHOOL_LOGO_DATABASE,
  SCHOOL_LOGO_DATABASE_MAP
}
`

fs.writeFileSync(JS_OUTPUT_PATH, js, 'utf8')
fs.writeFileSync(JSON_OUTPUT_PATH, JSON.stringify(SCHOOL_LOGO_DATABASE, null, 2), 'utf8')

const ready = SCHOOL_LOGO_DATABASE.filter((record) => record.localPath || record.cachedFileID || record.imageUrl).length
const failed = SCHOOL_LOGO_DATABASE.filter((record) => record.cacheStatus && record.cacheStatus !== 'ok').length
console.log(`Wrote ${SCHOOL_LOGO_DATABASE.length} logo database records`)
console.log(`Ready logos: ${ready}`)
console.log(`Not ready: ${SCHOOL_LOGO_DATABASE.length - ready}`)
console.log(`Cache failures: ${failed}`)
