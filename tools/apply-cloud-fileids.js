const fs = require('fs')
const path = require('path')
const { SCHOOL_LOGO_DATABASE } = require('../data/schoolLogoDatabase.generated')

const MAP_PATH = path.resolve(__dirname, '../cloud-database/school-logo-fileids.json')
const JS_OUTPUT_PATH = path.resolve(__dirname, '../data/schoolLogoDatabase.generated.js')
const JSON_OUTPUT_PATH = path.resolve(__dirname, '../data/schoolLogoDatabase.generated.json')

if (!fs.existsSync(MAP_PATH)) {
  console.error(`Missing fileID map: ${MAP_PATH}`)
  console.error('Expected shape: [{"school":"北京大学","cachedFileID":"cloud://.../school-logos/北京大学.png"}]')
  process.exit(1)
}

const fileIdRecords = JSON.parse(fs.readFileSync(MAP_PATH, 'utf8'))
const fileIdMap = fileIdRecords.reduce((map, item) => {
  if (item.school && item.cachedFileID) map[item.school] = item.cachedFileID
  return map
}, {})

const nextDatabase = SCHOOL_LOGO_DATABASE.map((record) => {
  const cachedFileID = fileIdMap[record.school] || record.cachedFileID || ''
  return Object.assign({}, record, {
    cachedFileID,
    status: cachedFileID ? 'cloud_cached' : record.status
  })
})

const js = `// Auto-generated by tools/build-school-logo-database.js or tools/apply-cloud-fileids.js
// This is the app-facing school logo database.

const SCHOOL_LOGO_DATABASE = ${JSON.stringify(nextDatabase, null, 2)}

const SCHOOL_LOGO_DATABASE_MAP = SCHOOL_LOGO_DATABASE.reduce((map, item) => {
  map[item.school] = item
  return map
}, {})

module.exports = {
  SCHOOL_LOGO_DATABASE,
  SCHOOL_LOGO_DATABASE_MAP
}
`

fs.writeFileSync(JS_OUTPUT_PATH, js, 'utf8')
fs.writeFileSync(JSON_OUTPUT_PATH, JSON.stringify(nextDatabase, null, 2), 'utf8')

const cloudCached = nextDatabase.filter((record) => record.cachedFileID).length
console.log(`Applied ${Object.keys(fileIdMap).length} fileIDs`)
console.log(`Cloud cached records: ${cloudCached}`)
