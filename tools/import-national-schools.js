const fs = require('fs')
const path = require('path')

const INPUT_PATH = process.argv[2]
const OUTPUT_PATH = path.resolve(__dirname, '../data/nationalSchools.generated.js')

if (!INPUT_PATH) {
  console.error('Usage: node tools/import-national-schools.js <schools.csv|schools.json>')
  process.exit(1)
}

const parseCsvLine = (line) => {
  const cells = []
  let current = ''
  let quoted = false
  for (let i = 0; i < line.length; i += 1) {
    const char = line[i]
    const next = line[i + 1]
    if (char === '"' && quoted && next === '"') {
      current += '"'
      i += 1
    } else if (char === '"') {
      quoted = !quoted
    } else if (char === ',' && !quoted) {
      cells.push(current)
      current = ''
    } else {
      current += char
    }
  }
  cells.push(current)
  return cells.map((cell) => cell.trim())
}

const parseCsv = (content) => {
  const lines = content.replace(/^\uFEFF/, '').split(/\r?\n/).filter(Boolean)
  const headerIndex = lines.findIndex((line) => parseCsvLine(line).includes('学校名称'))
  const headers = parseCsvLine(lines[headerIndex >= 0 ? headerIndex : 0])
  return lines.slice((headerIndex >= 0 ? headerIndex : 0) + 1).map((line) => {
    const cells = parseCsvLine(line)
    return headers.reduce((item, header, index) => {
      item[header] = cells[index] || ''
      return item
    }, {})
  })
}

const pick = (row, keys) => keys.map((key) => row[key]).find(Boolean) || ''

const normalizeSchool = (row) => {
  const name = pick(row, ['school_name', 'name', '学校名称', '学校名', '院校名称', '高校名称'])
  if (!name) return null
  if (/^[\u4e00-\u9fa5]+[市省区]（\d+所）$/.test(name)) return null
  const levelRaw = pick(row, ['level', '办学层次', '层次', 'type', 'school_type'])
  const typeRaw = pick(row, ['类型', '院校类型', 'school_nature', 'nature', '办学类型'])
  return {
    name,
    province: pick(row, ['province', '所在地', '省份', '所在地省份', '主管部门所在地']) || '待补充',
    city: pick(row, ['city', '城市', '所在地市']) || '',
    type: typeRaw || levelRaw || '综合',
    level: levelRaw || '',
    department: pick(row, ['department', '主管部门', '主管单位']) || '',
    code: pick(row, ['code', 'school_code', '院校代码', '学校标识码']) || ''
  }
}

const readInput = (filePath) => {
  const absolutePath = path.resolve(filePath)
  const content = fs.readFileSync(absolutePath, 'utf8')
  if (absolutePath.endsWith('.json')) return JSON.parse(content)
  return parseCsv(content)
}

const rows = readInput(INPUT_PATH)
const seen = new Set()
const schools = rows
  .map(normalizeSchool)
  .filter(Boolean)
  .filter((school) => {
    if (seen.has(school.name)) return false
    seen.add(school.name)
    return true
  })
  .sort((a, b) => a.name.localeCompare(b.name, 'zh-CN'))

const js = `// Auto-generated by tools/import-national-schools.js
// Full school master list used by the logo database.

const NATIONAL_SCHOOLS = ${JSON.stringify(schools, null, 2)}

module.exports = {
  NATIONAL_SCHOOLS
}
`

fs.writeFileSync(OUTPUT_PATH, js, 'utf8')
console.log(`Imported ${schools.length} schools`)
console.log(OUTPUT_PATH)
