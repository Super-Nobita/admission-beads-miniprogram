const fs = require('fs')
const path = require('path')
const { GENERATED_LOGO_CACHE } = require('../data/schoolLogoCache.generated')

const GALLERY_URL = 'https://www.urongda.com/gallery'
const IMAGE_BASE_URL = 'https://www.urongda.com/images/webp'
const ASSET_DIR = path.resolve(__dirname, '../assets/school-logos')
const OUTPUT_PATH = path.resolve(__dirname, '../data/schoolLogoCache.generated.js')
const MAX_LOGOS = Number(process.env.MAX_LOGOS || 0)
const DELAY_MS = Number(process.env.DELAY_MS || 80)
const LEGACY_GALLERY_FILE_PATTERN = /^\/assets\/school-logos\/gallery-\d{4}-/

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

const slugify = (value) => value
  .normalize('NFKD')
  .replace(/[^\w\u4e00-\u9fa5-]+/g, '-')
  .replace(/-+/g, '-')
  .replace(/^-|-$/g, '')

const serialize = (records) => `// Auto-generated by tools/cache-urongda-gallery-logos.js
// Local files are stored under assets/school-logos.

const GENERATED_LOGO_CACHE = ${JSON.stringify(records, null, 2)}

module.exports = {
  GENERATED_LOGO_CACHE
}
`

const decodeFlightString = (value) => {
  try {
    return JSON.parse(`"${value.replace(/"/g, '\\"')}"`)
  } catch (error) {
    return value
  }
}

const extractSchools = (html) => {
  const names = new Set()
  const patterns = [
    /\{"name":"([^"]+)"\}/g,
    /\{\\"name\\":\\"([^"]+)\\"\}/g
  ]

  patterns.forEach((pattern) => {
    let match = pattern.exec(html)
    while (match) {
      const name = decodeFlightString(match[1]).trim()
      if (name && !name.includes('/')) names.add(name)
      match = pattern.exec(html)
    }
  })

  return Array.from(names).sort((a, b) => a.localeCompare(b, 'zh-CN'))
}

const imageUrlFor = (school) => `${IMAGE_BASE_URL}/${encodeURIComponent(school)}-240.webp`

const existingBySchool = new Map(GENERATED_LOGO_CACHE.map((record) => [record.school, record]))

const hasCachedFile = (record) => {
  if (!record || record.cacheStatus !== 'ok' || !record.localPath) return false
  if (LEGACY_GALLERY_FILE_PATTERN.test(record.localPath)) return false
  const relativePath = record.localPath.replace(/^\//, '')
  return fs.existsSync(path.resolve(__dirname, '..', relativePath))
}

const cacheOne = async (school, index) => {
  const existing = existingBySchool.get(school)
  if (hasCachedFile(existing)) {
    return existing
  }

  const imageUrl = imageUrlFor(school)
  const response = await fetch(imageUrl, {
    redirect: 'follow',
    headers: {
      'user-agent': 'Mozilla/5.0 school-logo-gallery-cache'
    }
  })

  if (!response.ok) {
    return Object.assign({}, existing || {}, {
      school,
      sourceName: 'Urongda 高校校徽图鉴',
      sourceUrl: GALLERY_URL,
      imageUrl,
      localPath: '',
      cacheStatus: 'not_found',
      cacheMessage: `HTTP ${response.status}`
    })
  }

  const contentType = response.headers.get('content-type') || ''
  if (!contentType.toLowerCase().includes('image/webp')) {
    return Object.assign({}, existing || {}, {
      school,
      sourceName: 'Urongda 高校校徽图鉴',
      sourceUrl: GALLERY_URL,
      imageUrl,
      localPath: '',
      cacheStatus: 'not_direct_image',
      cacheMessage: contentType
    })
  }

  const buffer = Buffer.from(await response.arrayBuffer())
  const fileName = `gallery-${slugify(school)}.webp`
  const absolutePath = path.join(ASSET_DIR, fileName)
  fs.mkdirSync(ASSET_DIR, { recursive: true })
  fs.writeFileSync(absolutePath, buffer)

  return Object.assign({}, existing || {}, {
    school,
    province: (existing && existing.province) || '',
    type: (existing && existing.type) || '',
    status: 'local_cached',
    sourceName: (existing && existing.sourceName) || 'Urongda 高校校徽图鉴',
    sourceUrl: (existing && existing.sourceUrl) || GALLERY_URL,
    imageUrl,
    downloadUrl: (existing && existing.downloadUrl) || '',
    cachedFileID: (existing && existing.cachedFileID) || '',
    licenseNote: (existing && existing.licenseNote) || '第三方图鉴来源；上线前建议核对学校官方视觉规范，并转存为微信云缓存',
    localPath: `/assets/school-logos/${fileName}`,
    cacheStatus: 'ok',
    cacheMessage: ''
  })
}

const main = async () => {
  const galleryResponse = await fetch(GALLERY_URL, {
    redirect: 'follow',
    headers: {
      'user-agent': 'Mozilla/5.0 school-logo-gallery-cache'
    }
  })

  if (!galleryResponse.ok) {
    throw new Error(`Failed to fetch gallery: HTTP ${galleryResponse.status}`)
  }

  const html = await galleryResponse.text()
  const schools = extractSchools(html)
  if (schools.length === 0) {
    throw new Error('No school names found in gallery HTML')
  }

  const existingOkCount = schools.filter((school) => {
    return hasCachedFile(existingBySchool.get(school))
  }).length

  const targets = schools
    .filter((school) => !hasCachedFile(existingBySchool.get(school)))
    .slice(0, MAX_LOGOS || undefined)

  console.log(`Gallery schools found: ${schools.length}`)
  console.log(`Already cached from gallery/name match: ${existingOkCount}`)
  console.log(`New cache targets: ${targets.length}`)

  const recordsBySchool = new Map(GENERATED_LOGO_CACHE.map((record) => [record.school, record]))
  for (let index = 0; index < targets.length; index += 1) {
    const school = targets[index]
    process.stdout.write(`Caching ${index + 1}/${targets.length} ${school}... `)
    const cached = await cacheOne(school, index)
    recordsBySchool.set(school, cached)
    process.stdout.write(`${cached.cacheStatus}\n`)
    await sleep(DELAY_MS)
  }

  const merged = Array.from(recordsBySchool.values())
    .sort((a, b) => a.school.localeCompare(b.school, 'zh-CN'))

  fs.writeFileSync(OUTPUT_PATH, serialize(merged), 'utf8')
  const cachedCount = merged.filter((record) => record.cacheStatus === 'ok' && record.localPath).length
  console.log(`Wrote ${merged.length} cache records to ${OUTPUT_PATH}`)
  console.log(`Cached local logo files: ${cachedCount}`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
